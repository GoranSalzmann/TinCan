import { COMPOSE_SERVICES } from "./monitoring.js";

/** Files `tincan init` writes (14 §4). Kept as code so the CLI is a single artifact (14 §9). */

export interface InitValues {
  /** Host name, or `localhost` for a trial run over plain HTTP. */
  domain: string;
  acmeEmail: string;
  instanceName: string;
  /** True: Caddy serves plain HTTP on `httpPort` (local trial). False: HTTPS on 80/443 with automatic certificates. */
  insecureHttp: boolean;
  httpPort: number;
  publicUrl: string;
  instanceSecret: string;
  livekitKey: string;
  livekitSecret: string;
  /** Bearer token for Prometheus (`GET /api/v1/metrics`), and the Grafana admin password (14 §8). */
  metricsToken: string;
  grafanaPassword: string;
  /** Name Caddy gets a certificate for and LiveKit's TURN/TLS serves; null leaves TURN off (14 §2.3). */
  turnDomain: string | null;
  /** The Docker host gateway: LiveKit's HTTP port also listens here so Caddy and the app can reach it (18 T26). */
  hostGatewayIp: string;
  uid: number;
  gid: number;
  /** Relative path from the output directory to the repository, when building images from source. */
  repoDir: string | null;
  image: string;
}

export function envFile(v: InitValues): string {
  return `# Generated by \`tincan init\`. Secrets: keep this file private.
TINCAN_SECURITY__INSTANCE_SECRET=${v.instanceSecret}
TINCAN_INSTANCE__PUBLIC_URL=${v.publicUrl}
TINCAN_LIVEKIT__URL=${v.insecureHttp ? "ws" : "wss"}://${v.domain}${v.insecureHttp ? `:${v.httpPort}` : ""}/livekit
TINCAN_LIVEKIT__API_URL=http://host.docker.internal:7880
TINCAN_LIVEKIT__API_KEY=${v.livekitKey}
TINCAN_LIVEKIT__API_SECRET=${v.livekitSecret}
TINCAN_MODULES__METRICS__TOKEN=${v.metricsToken}

# Used by docker-compose.yml and the Caddyfile.
DOMAIN=${v.domain}
ACME_EMAIL=${v.acmeEmail}
HTTP_PORT=${v.httpPort}
TURN_DOMAIN=${v.turnDomain ?? ""}
HOST_UID=${v.uid}
HOST_GID=${v.gid}
GRAFANA_PASSWORD=${v.grafanaPassword}
`;
}

export function configFile(v: InitValues): string {
  return `# Tin Can configuration (04 §9). Secrets live in .env, not here.
# Every setting can also be set with an environment variable: TINCAN_ADAPTERS__DATABASE__PATH=...
instance:
  name: ${JSON.stringify(v.instanceName)}
  publicUrl: ${v.publicUrl}
server:
  host: 0.0.0.0
  port: 3000
  trustProxy: true # the app sits behind Caddy
dataDir: /data
adapters:
  database: { kind: sqlite, path: /data/app.db }
  storage: { kind: local, path: /data/files }
  pubsub: { kind: memory }
  auth: { kinds: [local] }
modules:
  accounts: { signup: invite-only }
log:
  level: info
`;
}

export function composeFile(v: InitValues): string {
  const build = (target: string) =>
    v.repoDir
      ? `    build:
      context: ${v.repoDir}
      dockerfile: deploy/Dockerfile
      target: ${target}
`
      : "";
  return `# Generated by \`tincan init\`.
name: tincan
services:
  tincan:
${build("server")}    image: ${v.image}-server
    restart: unless-stopped
    user: "\${HOST_UID:-1000}:\${HOST_GID:-1000}"
    env_file: .env
    environment:
      TINCAN_CONFIG: /config/config.yaml
    volumes:
      - ./data:/data
      - ./config.yaml:/config/config.yaml:ro
    # LiveKit (host networking) posts webhooks here; Caddy reaches the app over the compose network (14 §2).
    ports:
      - "127.0.0.1:3000:3000"
    # The app reaches LiveKit's API through the Docker host gateway (18 T26).
    extra_hosts:
      - "host.docker.internal:host-gateway"
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3000/readyz').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))"]
      interval: 15s
      timeout: 5s
      retries: 5
      start_period: 20s

  caddy:
${build("web")}    image: ${v.image}-web
    restart: unless-stopped
    depends_on: [tincan]
    ports:
      - "${v.insecureHttp ? "${HTTP_PORT:-8080}:80" : "80:80"}"${
        v.insecureHttp
          ? ""
          : `
      - "443:443"
      - "443:443/udp"`
      }
    env_file: .env
    # Host networking for LiveKit means its HTTP port is reached through the Docker host gateway (14 §2, 18 T26).
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config

  # Voice. Start it with: docker compose --profile voice up -d
  # The version is pinned: the tested one is part of each Tin Can release (14 §7, 18 K-03).
  livekit:
    profiles: [voice]
    image: ${LIVEKIT_IMAGE}
    restart: unless-stopped
    network_mode: host
    command: ["--config", "/etc/livekit.yaml"]
    volumes:
      - ./livekit.yaml:/etc/livekit.yaml:ro
      # Caddy's certificates, read-only, for TURN/TLS. LiveKit loads them at start only (18 D6, T30).
      - caddy-data:/caddy:ro

${COMPOSE_SERVICES}
volumes:
  caddy-data:
  caddy-config:
`;
}

export function caddyfile(v: InitValues): string {
  const routes = `	encode zstd gzip
	@internal path /api/internal/* /api/v1/internal/* /api/v1/metrics
	handle @internal {
		respond 404
	}
	handle /api/* {
		reverse_proxy tincan:3000
	}
	handle /gateway {
		reverse_proxy tincan:3000
	}
	handle /files/* {
		reverse_proxy tincan:3000
	}
	handle /livekit/rtc* {
		uri strip_prefix /livekit
		reverse_proxy host.docker.internal:7880
	}
	# Build files carry a hash in their name; the worker and manifest must be re-checked on every load.
	header /assets/* Cache-Control "public, max-age=31536000, immutable"
	@pwa path /sw.js /manifest.webmanifest
	header @pwa Cache-Control "no-cache"
	handle {
		root * /srv/web
		try_files {path} /index.html
		file_server
	}`;
  // The TURN name only exists so Caddy obtains a certificate for it; LiveKit reads the files from the volume.
  const turnSite =
    v.turnDomain && !v.insecureHttp
      ? `
{$TURN_DOMAIN} {
	respond 404
}
`
      : "";
  const scheme = v.insecureHttp ? "ws" : "wss";
  // Scripts and styles only from self; Radix positions popovers with inline style attributes, hence style-src-attr.
  const csp = `default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; style-src 'self'; style-src-attr 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' blob:; font-src 'self'; connect-src 'self' ${scheme}://{hostport}; worker-src 'self' blob:; frame-ancestors 'none'; base-uri 'none'; form-action 'self'`;
  const headers = `	header {
		X-Content-Type-Options nosniff
		Referrer-Policy no-referrer
		Permissions-Policy "camera=(self), microphone=(self), display-capture=(self), geolocation=()"
		Cross-Origin-Opener-Policy same-origin
		Content-Security-Policy "${csp}"${v.insecureHttp ? "" : `\n		Strict-Transport-Security "max-age=31536000"`}
	}`;
  if (v.insecureHttp) {
    return `# Generated by \`tincan init\` (plain HTTP trial run: do not expose to the internet).
{
	auto_https off
}
:80 {
${routes}
${headers}
}
`;
  }
  // `email` with no argument is a Caddy parse error, so the block exists only when an address was given.
  const acme = v.acmeEmail
    ? `{
	email {$ACME_EMAIL}
}
`
    : "";
  return `# Generated by \`tincan init\`.
${acme}{$DOMAIN} {
${routes}
${headers}
}
${turnSite}`;
}

/** The LiveKit image every generated compose file uses; bumped together with the release (14 §7). */
export const LIVEKIT_IMAGE = "livekit/livekit-server:v1.13.10";

const CADDY_CERTS = "/caddy/caddy/certificates/acme-v02.api.letsencrypt.org-directory";

export function livekitFile(v: InitValues): string {
  const certs = v.turnDomain ? `${CADDY_CERTS}/${v.turnDomain}/${v.turnDomain}` : "";
  const turn = v.turnDomain
    ? `turn:
  enabled: true
  domain: ${v.turnDomain}
  tls_port: 5349
  udp_port: 3478
  cert_file: ${certs}.crt
  key_file: ${certs}.key`
    : `# TURN is off until a second DNS name points at this machine and Caddy has a certificate for it (14 §2.3).
# Re-run \`tincan init --turn-domain turn.${v.domain}\` in a new directory to see the lines to add:
turn:
  enabled: false`;
  return `# LiveKit configuration (14 §2.2), checked against ${LIVEKIT_IMAGE} in spikes D1 and D6.
port: 7880
# The HTTP port (signalling and the admin API) listens on loopback and the Docker host gateway only. The media ports
# below are not affected by this setting (D6). Keep 7880 closed in the host firewall as well (T26).
bind_addresses:
  - 127.0.0.1
  - ${v.hostGatewayIp}
rtc:
  tcp_port: 7881
  udp_port: 7882 # one UDP port for all media (18 T4): one firewall rule
  use_external_ip: true
room:
  empty_timeout: 60
  departure_timeout: 20
${turn}
keys:
  ${v.livekitKey}: ${v.livekitSecret}
webhook:
  api_key: ${v.livekitKey}
  urls:
    - http://127.0.0.1:3000/api/v1/internal/livekit/webhook
`;
}
