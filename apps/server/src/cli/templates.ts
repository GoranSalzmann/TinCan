/** Files `tincan init` writes (14 §4). Kept as code so the CLI is a single artifact (14 §9). */

export interface InitValues {
  /** Host name, or `localhost` for a trial run over plain HTTP. */
  domain: string;
  acmeEmail: string;
  instanceName: string;
  /** True: Caddy serves plain HTTP on `httpPort` (local trial). False: HTTPS on 80/443 with automatic certificates. */
  insecureHttp: boolean;
  httpPort: number;
  publicUrl: string;
  instanceSecret: string;
  livekitKey: string;
  livekitSecret: string;
  uid: number;
  gid: number;
  /** Relative path from the output directory to the repository, when building images from source. */
  repoDir: string | null;
  image: string;
}

export function envFile(v: InitValues): string {
  return `# Generated by \`tincan init\`. Secrets: keep this file private.
TINCAN_SECURITY__INSTANCE_SECRET=${v.instanceSecret}
TINCAN_INSTANCE__PUBLIC_URL=${v.publicUrl}
TINCAN_LIVEKIT__URL=${v.insecureHttp ? "ws" : "wss"}://${v.domain}${v.insecureHttp ? `:${v.httpPort}` : ""}/livekit
TINCAN_LIVEKIT__API_KEY=${v.livekitKey}
TINCAN_LIVEKIT__API_SECRET=${v.livekitSecret}

# Used by docker-compose.yml and the Caddyfile.
DOMAIN=${v.domain}
ACME_EMAIL=${v.acmeEmail}
HTTP_PORT=${v.httpPort}
HOST_UID=${v.uid}
HOST_GID=${v.gid}
`;
}

export function configFile(v: InitValues): string {
  return `# Tin Can configuration (04 §9). Secrets live in .env, not here.
# Every setting can also be set with an environment variable: TINCAN_ADAPTERS__DATABASE__PATH=...
instance:
  name: ${JSON.stringify(v.instanceName)}
  publicUrl: ${v.publicUrl}
server:
  host: 0.0.0.0
  port: 3000
  trustProxy: true # the app sits behind Caddy
dataDir: /data
adapters:
  database: { kind: sqlite, path: /data/app.db }
  storage: { kind: local, path: /data/files }
  pubsub: { kind: memory }
  auth: { kinds: [local] }
modules:
  accounts: { signup: invite-only }
log:
  level: info
`;
}

export function composeFile(v: InitValues): string {
  const build = (target: string) =>
    v.repoDir
      ? `    build:
      context: ${v.repoDir}
      dockerfile: deploy/Dockerfile
      target: ${target}
`
      : "";
  return `# Generated by \`tincan init\`.
name: tincan
services:
  tincan:
${build("server")}    image: ${v.image}-server
    restart: unless-stopped
    user: "\${HOST_UID:-1000}:\${HOST_GID:-1000}"
    env_file: .env
    environment:
      TINCAN_CONFIG: /config/config.yaml
    volumes:
      - ./data:/data
      - ./config.yaml:/config/config.yaml:ro
    # LiveKit (host networking) posts webhooks here; Caddy reaches the app over the compose network (14 §2).
    ports:
      - "127.0.0.1:3000:3000"
    read_only: true
    tmpfs: [/tmp]
    cap_drop: [ALL]
    security_opt: ["no-new-privileges:true"]
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:3000/readyz').then(r=>process.exit(r.ok?0:1),()=>process.exit(1))"]
      interval: 15s
      timeout: 5s
      retries: 5
      start_period: 20s

  caddy:
${build("web")}    image: ${v.image}-web
    restart: unless-stopped
    depends_on: [tincan]
    ports:
      - "${v.insecureHttp ? "${HTTP_PORT:-8080}:80" : "80:80"}"${
        v.insecureHttp
          ? ""
          : `
      - "443:443"
      - "443:443/udp"`
      }
    env_file: .env
    # Host networking for LiveKit means its HTTP port is reached through the Docker host gateway (14 §2, 18 T26).
    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy-data:/data
      - caddy-config:/config

  # Not used by M1 (no voice module yet). Start it with: docker compose --profile voice up -d
  livekit:
    profiles: [voice]
    image: livekit/livekit-server # pin a version before enabling (spike D1, 18 K-03)
    restart: unless-stopped
    network_mode: host
    command: ["--config", "/etc/livekit.yaml"]
    volumes:
      - ./livekit.yaml:/etc/livekit.yaml:ro

volumes:
  caddy-data:
  caddy-config:
`;
}

export function caddyfile(v: InitValues): string {
  const routes = `	encode zstd gzip
	handle /api/internal/* {
		respond 404
	}
	handle /api/* {
		reverse_proxy tincan:3000
	}
	handle /gateway {
		reverse_proxy tincan:3000
	}
	handle /files/* {
		reverse_proxy tincan:3000
	}
	handle /livekit/rtc* {
		uri strip_prefix /livekit
		reverse_proxy host.docker.internal:7880
	}
	handle {
		root * /srv/web
		try_files {path} /index.html
		file_server
	}`;
  const scheme = v.insecureHttp ? "ws" : "wss";
  // Scripts and styles only from self; Radix positions popovers with inline style attributes, hence style-src-attr.
  const csp = `default-src 'self'; script-src 'self'; style-src 'self'; style-src-attr 'unsafe-inline'; img-src 'self' data: blob:; media-src 'self' blob:; font-src 'self'; connect-src 'self' ${scheme}://{host}; worker-src 'self' blob:; frame-ancestors 'none'; base-uri 'none'; form-action 'self'`;
  const headers = `	header {
		X-Content-Type-Options nosniff
		Referrer-Policy no-referrer
		Permissions-Policy "camera=(self), microphone=(self), display-capture=(self)"
		Content-Security-Policy "${csp}"${v.insecureHttp ? "" : `\n		Strict-Transport-Security "max-age=31536000"`}
	}`;
  if (v.insecureHttp) {
    return `# Generated by \`tincan init\` (plain HTTP trial run: do not expose to the internet).
{
	auto_https off
}
:80 {
${routes}
${headers}
}
`;
  }
  return `# Generated by \`tincan init\`.
{
	email {$ACME_EMAIL}
}
{$DOMAIN} {
${routes}
${headers}
}
`;
}

export function livekitFile(v: InitValues): string {
  return `# LiveKit configuration (14 §2.2). Unused until the voice milestone; keys come from .env. (verify) in spike D1/D6.
port: 7880
rtc:
  tcp_port: 7881
  udp_port: 7882
  use_external_ip: true
keys:
  ${v.livekitKey}: ${v.livekitSecret}
webhook:
  api_key: ${v.livekitKey}
  urls:
    - http://127.0.0.1:3000/api/internal/livekit/webhook
`;
}
