import { z } from "zod";

/** Core configuration (04 §9). Unknown keys are an error, which catches typos. */
export const CoreConfigSchema = z.strictObject({
  instance: z
    .strictObject({
      /** Default community name, used when the first-run setup does not choose another. */
      name: z.string().trim().min(1).max(64).default("Tin Can"),
      /** Public origin clients use, e.g. https://chat.example.com. Decides cookie `Secure` and the WebSocket origin check. */
      publicUrl: z.url().default("http://localhost:3000"),
      /** AGPL section 13: where users of this instance can get its source code. */
      sourceUrl: z.url().optional(),
    })
    .prefault({}),
  server: z
    .strictObject({
      host: z.string().default("0.0.0.0"),
      port: z.number().int().min(0).max(65535).default(3000),
      /** True behind Caddy so the client IP comes from X-Forwarded-For. Never true when exposed directly. */
      trustProxy: z.boolean().default(false),
      /** Extra browser origins allowed to open the gateway (dev servers). The public URL is always allowed. */
      allowedOrigins: z.array(z.url()).default([]),
    })
    .prefault({}),
  /** Holds the setup token and pre-migration backups. */
  dataDir: z.string().min(1).default("./data"),
  security: z.strictObject({
    /** Keys IP hashes in the session list and the voice E2EE keys. Generated by `tincan init`; supply via env or `*_FILE`. */
    instanceSecret: z.string().min(32, "must be at least 32 characters (tincan init generates one)"),
    /**
     * Per-minute ceilings on API calls (15 §4.2, S-11): a signed-in member's reads and writes, and everything from one
     * address. Far above what the web client does (an initial load is about 20 calls); they bound a script or a flood.
     */
    rateLimit: z
      .strictObject({
        readsPerMinute: z.number().int().min(10).default(600),
        writesPerMinute: z.number().int().min(5).default(120),
        perIpPerMinute: z.number().int().min(10).default(1200),
        /** Open gateway sessions per member (the oldest ends when a new one starts) and open sockets per address. */
        gatewaySessionsPerUser: z.number().int().min(1).default(30),
        gatewaySocketsPerIp: z.number().int().min(1).default(60),
      })
      .prefault({}),
  }),
  adapters: z
    .strictObject({
      database: z.strictObject({ kind: z.literal("sqlite"), path: z.string().min(1) }).prefault({
        kind: "sqlite",
        path: "./data/app.db",
      }),
      storage: z.strictObject({ kind: z.literal("local"), path: z.string().min(1) }).prefault({
        kind: "local",
        path: "./data/files",
      }),
      pubsub: z.strictObject({ kind: z.literal("memory") }).prefault({ kind: "memory" }),
      auth: z.strictObject({ kinds: z.array(z.literal("local")).min(1) }).prefault({ kinds: ["local"] }),
    })
    .prefault({}),
  /** The voice server (08, 14 §2). Without it the voice module stays off. */
  livekit: z
    .strictObject({
      /** Public signalling URL handed to clients, e.g. wss://chat.example.com/livekit. */
      url: z.string(),
      /** Internal HTTP URL of the LiveKit API; the compose file reaches the host-networked server through the Docker host gateway. */
      apiUrl: z.string().default("http://127.0.0.1:7880"),
      apiKey: z.string(),
      apiSecret: z.string(),
    })
    .optional(),
  log: z
    .strictObject({
      level: z.enum(["trace", "debug", "info", "warn", "error", "silent"]).default("info"),
    })
    .prefault({}),
  /** Per-module sections; validated against each enabled module's own schema by the loader. */
  modules: z.record(z.string(), z.unknown()).default({}),
});

export type CoreConfig = z.infer<typeof CoreConfigSchema>;

export function sourceUrlOf(config: CoreConfig, fallback: string): string {
  return config.instance.sourceUrl ?? fallback;
}
